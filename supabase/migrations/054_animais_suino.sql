-- Execute no SQL Editor do Supabase (Dashboard → SQL Editor → New Query → Run)
-- Rodar DEPOIS da migration 047 (tipo do animal).
-- DEPOIS desta, rode a 055_animais_suino_racas.sql — são DUAS execuções.
-- ============================================================================
-- Por que este arquivo é só uma linha:
--   ALTER TYPE ... ADD VALUE só vale depois de COMMIT. Enquanto a transação
--   que criou o valor não fecha, qualquer uso de 'suino' na mesma execução
--   morre com "unsafe use of new value" e DERRUBA O ARQUIVO INTEIRO — inclusive
--   o próprio ALTER TYPE, que volta atrás junto. Rodar de novo dá o mesmo erro,
--   para sempre: o arquivo nunca chega ao fim sozinho.
--
--   Por isso as raças foram para a 055. Aviso em comentário não resolve (Ctrl+A
--   e Run ignora comentário) — arquivos separados resolvem.
--
--   A CATEGORIA continua saindo sozinha da idade + sexo (view v_animals) e
--   continua com as mesmas três chaves — elas são o PAPEL do animal, não o
--   nome dele. Quem dá nome é a tela: leitão/leitoa (filhote), porco (macho
--   adulto), porca (fêmea adulta). Por isso a view NÃO precisa ser recriada:
--   nada muda nas colunas dela.
-- ============================================================================

ALTER TYPE animal_species ADD VALUE IF NOT EXISTS 'suino';
